import type { Problem, SolutionResponse } from './types'
import { cleanText, cap, fmtDateLong } from './format'

/** Markdown export of everything shown on the detail page (real data only). */
export function buildResearchMarkdown(p: Problem, related: Problem[], ai?: SolutionResponse): string {
  const L: string[] = []
  L.push(`# ${p.title}`, '')
  L.push(`- **Category:** ${p.category}`)
  if (p.subreddit) L.push(`- **Source:** r/${p.subreddit}`)
  if (p.createdMs) L.push(`- **Posted:** ${fmtDateLong(p.createdMs)}`)
  L.push(`- **Upvotes:** ${p.upvotes ?? 'n/a'} · **Comments:** ${p.comments}`)
  if (p.url) L.push(`- **Link:** ${p.url}`)
  if (p.oppScore !== null) L.push(`- **Opportunity score:** ${Math.round(p.oppScore * 100)}/100`)
  if (p.sentiment) L.push(`- **Sentiment:** ${p.sentiment}${p.intensity !== null ? ` (complaint intensity ${p.intensity.toFixed(2)})` : ''}`)
  if (p.keywords.length) L.push(`- **Topic keywords:** ${p.keywords.join(', ')}`)
  const body = cleanText(p.content, 1200)
  if (body) L.push('', '## What the post says', '', body)
  if (related.length) {
    L.push('', '## Related discussions', '')
    related.slice(0, 5).forEach((r) => L.push(`- ${r.title} — r/${r.subreddit}, ${r.upvotes ?? 0} upvotes${r.url ? ` (${r.url})` : ''}`))
  }
  if (ai) {
    const a = ai.analysis
    L.push('', '## Underlying problem', '', a.problem_statement, '', '## Business hypotheses', '')
    a.solutions.forEach((s, i) => L.push(`${i + 1}. **${s.idea}**`, `   - How it works: ${s.how_it_works}`, `   - Why it works: ${s.why_it_works}`))
    L.push('', `**Target audience:** ${a.target_audience}`, '', `**Monetization:** ${a.monetization}`, '',
      `**Market size:** ${cap(a.market_size)} · **Difficulty:** ${cap(a.difficulty)}`)
    L.push('', `_AI synthesis generated by ${ai.model_used ?? 'the backend model'}. Treat as hypotheses to validate._`)
  }
  return L.join('\n')
}

export function buildValidationMarkdown(p: Problem, items: string[]): string {
  return [`# Validation plan — ${p.title}`, '', ...items.map((i) => `- [ ] ${i}`), ''].join('\n')
}
